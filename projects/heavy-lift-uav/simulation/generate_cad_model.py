        fig = plt.figure(figsize=(10, 8), dpi=300)
        ax = fig.add_subplot(111, projection='3d')
        ax.set_facecolor('#FFFFFF')
        
        # Draw base geometry
        ax.plot([-0.20, 0.20], [0, 0], [0.04, 0.04], color='#2D3748', linewidth=4)
        ax.plot([0, 0], [-0.20, 0.20], [0.04, 0.04], color='#2D3748', linewidth=4)
        
        for idx, d in enumerate(directions):
            end_xy = arm_length * np.array(d)
            ax.plot([0, end_xy[0]], [0, end_xy[1]], [0, 0], color='#1A202C', linewidth=5)
            ax.plot([end_xy[0]], [end_xy[1]], [0.045], 'o', color='#CBD5E0', markersize=9)
            prop_dir = np.array([-d[1], d[0], 0])
            p1 = end_xy + prop_length * prop_dir[:2]
            p2 = end_xy - prop_length * prop_dir[:2]
            ax.plot([p1[0], p2[0]], [p1[1], p2[1]], [0.068], color='#2B6CB0', linewidth=3.5)

        ax.bar3d(-0.15, -0.10, -0.255, 0.30, 0.20, 0.15, color='#DD6B20', alpha=0.85)
        ax.scatter([0.18], [0.0], [-0.125], color='#1A202C', s=140)
        ax.plot([0.18, 0.205], [0, 0], [-0.125, -0.125], color='#3182CE', linewidth=4)
        ax.plot([0, 0], [0.08, 0.08], [0.04, 0.16], color='#E53E3E', linewidth=2.5)

        # Landing Gear
        ax.plot([-0.2, -0.2], [-0.45, 0.45], [-0.45, -0.45], color='#4A5568', linewidth=3.5)
        ax.plot([0.2, 0.2], [-0.45, 0.45], [-0.45, -0.45], color='#4A5568', linewidth=3.5)
        ax.plot([-0.2, -0.2], [0.2, 0.2], [0, -0.45], color='#4A5568', linewidth=2)
        ax.plot([0.2, 0.2], [0.2, 0.2], [0, -0.45], color='#4A5568', linewidth=2)
        ax.plot([-0.27, -0.13], [0.2, 0.2], [-0.455, -0.455], color='#1A202C', linewidth=6)
        ax.plot([0.13, 0.27], [0.2, 0.2], [-0.455, -0.455], color='#1A202C', linewidth=6)

        # Annotations Callouts
        annotations = [
            ([1.12, 0, 0.07], [1.3, 0.4, 0.3], '40" 2-Blade Propeller\n(R=508mm, 104mm clearance)'),
            ([1.12, 0, 0.04], [1.35, -0.2, 0.1], 'Brushless Motor\n(TMotor U15 II)'),
            ([0.56, 0, 0.0], [0.7, 0.7, 0.3], 'Carbon Fiber Arm Tube\n(30mm OD x 1.12m)'),
            ([0.0, 0.0, 0.04], [-0.4, 0.6, 0.4], 'Center Frame Hex Plates\n(400mm Diameter)'),
            ([0.0, 0.08, 0.16], [-0.3, 0.3, 0.5], 'Telemetry Radio Antenna'),
            ([0.0, 0.0, -0.18], [-0.7, -0.6, -0.1], '10 kg Payload Cargo Bay\n(300x200x150mm)'),
            ([0.20, 0.0, -0.125], [0.6, -0.6, -0.3], 'EO Camera & 2-Axis Gimbal\n(Forward Lens Barrel)'),
            ([0.20, 0.2, -0.455], [0.6, 0.7, -0.5], 'Landing Gear & Skid Feet\n(450mm Height)')
        ]

        for target, text_pos, text in annotations:
            ax.plot([target[0], text_pos[0]], [target[1], text_pos[1]], [target[2], text_pos[2]], color='#E53E3E', linestyle='--', linewidth=1.2)
            ax.text(text_pos[0], text_pos[1], text_pos[2], text, fontsize=8, fontweight='bold', bbox=dict(boxstyle='round,pad=0.3', facecolor='#FEFCBF', edgecolor='#D69E2E', alpha=0.9))

        ax.set_xlabel('X (m)', fontsize=9)
        ax.set_ylabel('Y (m)', fontsize=9)
