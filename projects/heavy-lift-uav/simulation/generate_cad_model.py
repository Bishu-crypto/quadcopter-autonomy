    writer.add_box([0.15, 0, -0.11], [0.06, 0.07, 0.04])
    writer.add_cylinder([0.18, 0, -0.125], [0.205, 0, -0.125], radius=0.014, segments=10)

    # 5. Carbon Fiber Arms (6 arms configuration, length 1.12m)
    arm_length = 1.12
    angles_rad = np.radians([0, 60, 120, 180, 240, 300])
    directions = [[np.cos(a), np.sin(a)] for a in angles_rad]
    
    arm_radius = 0.015 # OD 30mm
    prop_length = (prop_diameter * 0.0254) / 2.0 # propeller radius 0.508m
    
    for d in directions:
        end_xy = arm_length * np.array(d)
        writer.add_cylinder([0, 0, 0], [end_xy[0], end_xy[1], 0], radius=arm_radius, segments=8)
        # Two-tier motor: stator + rotor bell
        writer.add_cylinder([end_xy[0], end_xy[1], 0.015], [end_xy[0], end_xy[1], 0.030], radius=0.020, segments=12)
        writer.add_cylinder([end_xy[0], end_xy[1], 0.030], [end_xy[0], end_xy[1], 0.065], radius=0.025, segments=12)
        
        # 2-Blade Propeller Representation
        prop_dir = np.array([-d[1], d[0], 0])
        p_start = np.array([end_xy[0], end_xy[1], 0.068])
        writer.add_cylinder(p_start - prop_length * prop_dir, p_start + prop_length * prop_dir, radius=0.010, segments=6)

    # 6. Landing Gear Skids & Foot Pads
