    writer.add_cylinder([0, 0, 0.04], [0, 0, 0.043], radius=0.20, segments=16)
    writer.add_cylinder([0, 0, -0.043], [0, 0, -0.04], radius=0.20, segments=16)
    
    # 2. Generator Box, Fuel Tank & Antenna
    writer.add_box([0, 0, 0.05], [0.16, 0.16, 0.12])
    writer.add_cylinder([0, 0, -0.18], [0, 0, -0.05], radius=0.10, segments=12)
