class OBJWriter:
    def __init__(self):
        self.vertices = []
        self.faces = []
        
    def add_box(self, center, dimensions):
        cx, cy, cz = center
        dx, dy, dz = dimensions
        hx, hy, hz = dx / 2.0, dy / 2.0, dz / 2.0
        
        base_idx = len(self.vertices) + 1
        corners = [
            [cx - hx, cy - hy, cz - hz],
            [cx + hx, cy - hy, cz - hz],
            [cx + hx, cy + hy, cz - hz],
            [cx - hx, cy + hy, cz - hz],
            [cx - hx, cy - hy, cz + hz],
            [cx + hx, cy - hy, cz + hz],
            [cx + hx, cy + hy, cz + hz],
            [cx - hx, cy + hy, cz + hz],
        ]
        self.vertices.extend(corners)
        
        box_faces = [
            [base_idx, base_idx+1, base_idx+2, base_idx+3],
            [base_idx+4, base_idx+5, base_idx+6, base_idx+7],
            [base_idx, base_idx+1, base_idx+5, base_idx+4],
            [base_idx+2, base_idx+3, base_idx+7, base_idx+6],
            [base_idx, base_idx+3, base_idx+7, base_idx+4],
            [base_idx+1, base_idx+2, base_idx+6, base_idx+5],
        ]
        self.faces.extend(box_faces)

    def add_cylinder(self, p1, p2, radius, segments=12):
        p1 = np.array(p1)
        p2 = np.array(p2)
        v = p2 - p1
        length = np.linalg.norm(v)
        if length == 0:
            return
        v = v / length
        
        not_v = np.array([1, 0, 0]) if abs(v[0]) < 0.9 else np.array([0, 1, 0])
        n1 = np.cross(v, not_v)
        n1 /= np.linalg.norm(n1)
        n2 = np.cross(v, n1)
        
        base_idx = len(self.vertices) + 1
        circle1 = []
        circle2 = []
        for i in range(segments):
            theta = 2.0 * np.pi * i / segments
            pt = radius * np.cos(theta) * n1 + radius * np.sin(theta) * n2
            circle1.append(p1 + pt)
            circle2.append(p2 + pt)
            
        self.vertices.extend(circle1)
        self.vertices.extend(circle2)
        
        for i in range(segments):
            next_i = (i + 1) % segments
            idx1 = base_idx + i
            idx2 = base_idx + next_i
            idx3 = base_idx + segments + next_i
            idx4 = base_idx + segments + i
            self.faces.append([idx1, idx2, idx3, idx4])

    def write_to_file(self, filepath):
        os.makedirs(os.path.dirname(filepath), exist_ok=True)
        with open(filepath, 'w') as f:
            f.write("# High-Fidelity OBJ Mesh Generated by UAV Design Suite\n")
            for v in self.vertices:
                f.write(f"v {v[0]:.6f} {v[1]:.6f} {v[2]:.6f}\n")
            for face in self.faces:
                f.write("f " + " ".join(str(idx) for idx in face) + "\n")
        print(f"CAD mesh saved to {filepath}")

